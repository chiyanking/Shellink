export type AuditActor = 'ai' | 'human' | 'system'
export type AuditEntry = 'MCP' | 'CLI' | '桌面端' | '后台服务'
export type AuditStatus = 'success' | 'error' | 'running' | 'waiting'
export type AuditEvent = {
  id: string
  sessionId: string
  actor: AuditActor
  operator: string
  entry: AuditEntry
  kind: 'command' | 'control' | 'connection' | 'input' | 'transfer'
  title: string
  startedAt: string
  duration: string
  status: AuditStatus
  input: string
  stdout: string
  stderr: string
  exitCode?: number
  sensitive?: boolean
}

export const actorLabels: Record<AuditActor, string> = {
  ai: 'AI',
  human: '人工',
  system: '系统',
}
export const auditStatuses: Record<
  AuditStatus,
  { label: string; tone: 'green' | 'amber' | 'blue' | 'neutral' }
> = {
  success: { label: '已完成', tone: 'green' },
  error: { label: '执行失败', tone: 'amber' },
  running: { label: '执行中', tone: 'blue' },
  waiting: { label: '等待输入', tone: 'amber' },
}

